public class Identifiers{

	byte a;
	short b;
	int c;
	long d;
	float e;
	double f;
	char g;
	boolean h;
	
	public static void main(String args[]){
	
	Identifiers id = new Identifiers();
	
	System.out.println("byte a : " +id.a);
	System.out.println("short b : " +id.b);
	System.out.println("int c : " +id.c);
	System.out.println("long d : " +id.d);
	System.out.println("float e : " +id.e);
	System.out.println("double f : " +id.f);
	System.out.println("byte g : " +id.g);
	System.out.println("byte h : " +id.h);
	}
}